"""US cash-equity sessions, with bounded exchange calendar coverage."""
from __future__ import annotations

from datetime import date, datetime, time, timedelta, timezone
from zoneinfo import ZoneInfo
from buyback_calendar import HOLIDAYS, SOURCES

NEW_YORK = ZoneInfo("America/New_York")
EARLY_CLOSES = {
    2025: {"07-03", "11-28", "12-24"},
    2026: {"11-27", "12-24"},
    2027: {"11-26"},
    2028: {"07-03", "11-24"},
}
CALENDAR_VERSION = "nyse-2025-2028-v1"


def as_date(value) -> date:
    return date.fromisoformat(str(value)[:10])


def is_session(value) -> bool:
    day = as_date(value)
    if day.year not in HOLIDAYS:
        raise ValueError(f"Exchange calendar does not cover {day.year}")
    return day.weekday() < 5 and day.strftime("%m-%d") not in HOLIDAYS[day.year]


def session_close(value) -> datetime:
    day = as_date(value)
    if not is_session(day):
        raise ValueError(f"{day} is not a trading session")
    hour = 13 if day.strftime("%m-%d") in EARLY_CLOSES[day.year] else 16
    return datetime.combine(day, time(hour), NEW_YORK)


def completed_session(now: datetime | None = None, delay_minutes: int = 10) -> str:
    current = now or datetime.now(timezone.utc)
    if current.tzinfo is None:
        current = current.replace(tzinfo=timezone.utc)
    local = current.astimezone(NEW_YORK)
    day = local.date()
    while not is_session(day) or current < session_close(day) + timedelta(minutes=delay_minutes):
        day -= timedelta(days=1)
    return day.isoformat()


def sessions_behind(value, expected: str | None = None, now: datetime | None = None) -> int | None:
    try:
        first, last = as_date(value), as_date(expected or completed_session(now))
        if first > last:
            return -1
        if first.year not in HOLIDAYS or last.year not in HOLIDAYS:
            return None
        total = 0
        while first < last:
            first += timedelta(days=1)
            total += is_session(first)
        return total
    except (ValueError, TypeError):
        return None


def stage_due(now: datetime | None = None) -> dict:
    current = now or datetime.now(timezone.utc)
    local = current.astimezone(NEW_YORK)
    day = local.date()
    if not is_session(day):
        return {"due": False, "reason": "market_closed", "session_date": str(day)}
    minutes = (current - session_close(day)).total_seconds() / 60
    # Suppress regular-close attempts on an early-close day and vice versa.
    due = minutes >= 10 and local.hour < 20
    return {"due": due, "session_date": str(day), "stage": "settled" if local.hour >= 18 else "reconciliation" if minutes >= 40 else "initial", "close_at": session_close(day).isoformat()}


def export_browser(path):
    import json
    from pathlib import Path
    config=json.dumps({'version':CALENDAR_VERSION,'holidays':{str(k):sorted(v) for k,v in HOLIDAYS.items()},'early':{str(k):sorted(v) for k,v in EARLY_CLOSES.items()}},separators=(',',':'))
    script='/* Generated by market_sessions.py --export-browser. */\n(function(global){\n\'use strict\';\nconst calendar='+config+';\n'+r'''
const fmt=new Intl.DateTimeFormat('en-US',{timeZone:'America/New_York',year:'numeric',month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',hourCycle:'h23'});
function parts(value){const p=Object.fromEntries(fmt.formatToParts(value).map(r=>[r.type,r.value]));return {day:`${p.year}-${p.month}-${p.day}`,hour:Number(p.hour),minute:Number(p.minute)};}
function day(value){if(!value)return null;if(/^\d{4}-\d{2}-\d{2}$/.test(String(value)))return String(value);const d=new Date(value);return Number.isFinite(d.getTime())?parts(d).day:null;}
function session(value){const y=value.slice(0,4);if(!calendar.holidays[y])return null;const weekday=new Date(value+'T12:00:00Z').getUTCDay();return weekday!==0&&weekday!==6&&!calendar.holidays[y].includes(value.slice(5));}
function shift(value,offset){const d=new Date(value+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+offset);return d.toISOString().slice(0,10);}
function completed(now=new Date()){const p=parts(now);let d=p.day;for(let i=0;i<370;i++){const open=session(d);if(open===null)return null;const close=calendar.early[d.slice(0,4)].includes(d.slice(5))?13:16;if(open&&(d<p.day||p.hour*60+p.minute>=close*60+10))return d;d=shift(d,-1);}return null;}
function age(value,now=new Date()){let first=day(value),last=completed(now);if(!first||!last)return null;if(first>last)return -1;let count=0;for(let i=0;first<last&&i<3700;i++){first=shift(first,1);const open=session(first);if(open===null)return null;count+=Number(open);}return count;}
global.MarketSessions={calendar,day,session,completed,age};
})(window);
'''
    Path(path).write_text(script,encoding='utf-8')


