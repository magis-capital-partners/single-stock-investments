/* Actual SPA routes with local artifacts and an unavailable API fallback. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require(process.env.SSI_PLAYWRIGHT_MODULE || 'playwright');
const root=path.resolve(__dirname,'../../../dashboard'),shots=process.env.BUYBACK_SCREENSHOT_DIR || require('node:os').tmpdir();
(async()=>{
 const browser=await chromium.launch({headless:true}),page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/*',async route=>{
   const u=new URL(route.request().url());if(u.hostname!=='dashboard.test')return route.abort();
   const rel=decodeURIComponent(u.pathname).replace(/^\//,'')||'index.html',file=path.resolve(root,rel);
   if(!file.startsWith(root+path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile())return route.fulfill({status:404,body:'{}'});
   return route.fulfill({body:fs.readFileSync(file),contentType:({'.html':'text/html','.js':'application/javascript','.json':'application/json','.css':'text/css','.svg':'image/svg+xml'})[path.extname(file)]||'text/plain'});
 });
 await page.goto('https://dashboard.test/#/ideas/rock');
 await page.locator('.aggregates-hero').waitFor({timeout:45000});
 assert.equal(await page.locator('[data-ag-peer]').inputValue(),'peers');
 assert.equal(await page.locator('[data-ag-ticker="GVA"]').count(),0);
 await page.locator('[data-ag-view="operations"]').click();
 await page.locator('[data-ag-ticker="VMC"]').click();
 await page.locator('.aggregates-detail .aggregates-trends').waitFor();
 assert.match(await page.locator('.aggregates-detail').innerText(),/11.33/);
 await page.screenshot({path:path.join(shots,'aggregates-desktop.png')});
 await page.locator('[data-ag-close]').click();
 await page.locator('[data-ag-query]').fill('no-matching-producer');
 assert.equal(await page.locator('[data-ag-ticker]').count(),0);
 await page.locator('[data-ag-query]').fill('');
 await page.locator('[data-ag-peer]').selectOption('all');
 assert.equal(await page.locator('[data-ag-ticker="GVA"]').count(),1);
 await page.locator('[data-ag-period]').selectOption('Q');
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'aggregates mobile overflow');
 await page.screenshot({path:path.join(shots,'aggregates-mobile.png')});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto('https://dashboard.test/#/insights/investors/directory');
 await page.locator('[data-manager-list] tbody tr').first().waitFor({timeout:45000});
 assert.ok(await page.locator('[data-manager-list] tbody tr').count()<=25);
 await page.locator('[data-manager]').first().click();
 await page.locator('[data-manager-detail] table').waitFor();
 await page.locator('[data-manager-search]').fill('no-matching-manager');
 assert.equal(await page.locator('[data-manager]').count(),0);
 await page.locator('[data-manager-search]').fill('');
 await page.screenshot({path:path.join(shots,'investors-directory-desktop.png')});
 await page.locator('.data-status-link').click();
 await page.locator('.data-status').waitFor();
 assert.equal(await page.locator('#consensus-period-select').count(),0);
 assert.doesNotMatch(await page.locator('#insights-content').innerText(),/TerminalValue candidate feeds/);
 await page.screenshot({path:path.join(shots,'data-status-desktop.png')});
 await page.goto('https://dashboard.test/#/insights/managers');
 await page.locator('[data-manager-list] tbody tr').first().waitFor();
 assert.match(page.url(),/investors\/directory/);
 await page.goto('https://dashboard.test/#/market-risk');
 await page.locator('.risk-freshness-bar').waitFor();
 await page.locator('[data-risk-refresh]').click();
 await page.screenshot({path:path.join(shots,'market-risk-desktop.png')});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false,'risk mobile overflow');
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({aggregates:true,investors:true,dataStatus:true,legacyRoutes:true,riskRefresh:true,mobile:true,pageErrors:errors.length}));
 await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1);});
